import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const result = await build({
  absWorkingDir: root,
  entryPoints: ["packages/worker/src/dashboard-client.ts"],
  bundle: true,
  write: false,
  platform: "browser",
  format: "iife",
  target: "es2022",
  minify: true,
  legalComments: "none",
});
// A string module keeps Worker bundlers from rewriting browser code or adding
// helpers that would be missing when executed in the page.
const source = `// Generated by pnpm build:dashboard. Do not edit.\nexport const dashboardScript = ${JSON.stringify(result.outputFiles[0].text)};\n`;
const target = new URL("../packages/worker/src/dashboard-script.generated.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== source)
    throw new Error("Dashboard bundle is stale; run pnpm build:dashboard");
} else {
  await writeFile(target, source);
}
